; 06_data.asm - パレットと CHR-ROM タイルデータ（16x16 縦シューティング自機）

; ===== パレット (PRG 内) =====
palette:
    ; BG パレット（未使用だがダミーで埋める）
    .db $0f, $00, $10, $30
    .db $0f, $00, $10, $30
    .db $0f, $00, $10, $30
    .db $0f, $00, $10, $30
    ; スプライトパレット 0:
    ;   色 1 = $12（青／機体ボディ）
    ;   色 2 = $16（赤／エンジン・アクセント）
    ;   色 3 = $30（白／機首・ハイライト）
    .db $0f, $12, $16, $30
    .db $0f, $12, $16, $30
    .db $0f, $12, $16, $30
    .db $0f, $12, $16, $30

; ===== 割り込みベクタ =====
    .pad $fffa
    .dw nmi
    .dw reset
    .dw irq

; ===== CHR-ROM ($0000-$1FFF) =====
; 自機は 2x2 タイル (16x16 px) で、タイル番号 2,3,4,5 に割り当てる:
;   [2][3]
;   [4][5]
;
; 16x16 のビット画
;   B = 色 1 (青／ボディ)、R = 色 2 (赤／エンジン)、W = 色 3 (白／機首・ハイライト)
;
;    Row 0:  .......W W.......   機首
;    Row 1:  .......W W.......
;    Row 2:  ......BW WB......
;    Row 3:  ......BW WB......
;    Row 4:  .....BBB BBB.....
;    Row 5:  .....BBB BBB.....
;    Row 6:  ....BBBB BBBB....
;    Row 7:  ...BRBBB BBBRB...   ← 上下タイルの境
;    Row 8:  ..BB.BBB BBB.BB..
;    Row 9:  .BBBBBBB BBBBBBB.   翼が広がる
;    Row 10: WB.BBBWB BWBBB.BW
;    Row 11: WB.BBBWB BWBBB.BW
;    Row 12: WB....BB BB....BW
;    Row 13: ....RRRR RRRR....   噴射
;    Row 14: ......RR RR......
;    Row 15: .......R R.......
chr_start:
    ; --- タイル 0: 透明 ---
    .db $00, $00, $00, $00, $00, $00, $00, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00

    ; --- タイル 1: 8x8 べた塗り（他のサンプルとの互換で残す） ---
    .db $ff, $ff, $ff, $ff, $ff, $ff, $ff, $ff
    .db $00, $00, $00, $00, $00, $00, $00, $00

    ; --- タイル 2: 自機 top-left ---
    ; plane 0 (B と W で 1)
    .db $01, $01, $03, $03, $07, $07, $0f, $17
    ; plane 1 (R と W で 1)
    .db $01, $01, $01, $01, $00, $00, $00, $08

    ; --- タイル 3: 自機 top-right ---
    .db $80, $80, $c0, $c0, $e0, $e0, $f0, $e8
    .db $80, $80, $80, $80, $00, $00, $00, $10

    ; --- タイル 4: 自機 bottom-left ---
    .db $37, $7f, $df, $df, $c3, $00, $00, $00
    .db $00, $00, $82, $82, $80, $0f, $03, $01

    ; --- タイル 5: 自機 bottom-right ---
    .db $ec, $fe, $fb, $fb, $c3, $00, $00, $00
    .db $00, $00, $41, $41, $01, $f0, $c0, $80

    ; CHR 残り（8KB まで）を 0 で埋める
    .dsb $2000 - ($ - chr_start), $00
