; 05_data.asm - PRG 末尾のパレットと CHR-ROM タイルデータ

; ===== パレット (PRG 内) =====
palette:
    ; BG パレット（未使用だがダミーで埋める）
    .db $0f, $00, $10, $30
    .db $0f, $00, $10, $30
    .db $0f, $00, $10, $30
    .db $0f, $00, $10, $30
    ; スプライトパレット 0: 色 1 = $30（白）
    .db $0f, $30, $10, $00
    .db $0f, $30, $10, $00
    .db $0f, $30, $10, $00
    .db $0f, $30, $10, $00

; ===== 割り込みベクタ =====
    .pad $fffa
    .dw nmi
    .dw reset
    .dw irq

; ===== CHR-ROM ($0000-$1FFF) =====
chr_start:
    ; タイル 0: 透明
    .db $00, $00, $00, $00, $00, $00, $00, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; タイル 1: 8x8 べた塗り
    .db $ff, $ff, $ff, $ff, $ff, $ff, $ff, $ff
    .db $00, $00, $00, $00, $00, $00, $00, $00

    .dsb $2000 - ($ - chr_start), $00
