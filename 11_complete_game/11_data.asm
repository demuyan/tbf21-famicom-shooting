; 11_data.asm - パレット、サインテーブル、CHR-ROM
;   10 章までのキャラ + 数字 / S/C/O/R/E に加えて、
;   タイトル / GAME OVER / LIFE 表示用の文字 (タイル $1F..$2B) を追加。

;   このファイルは命令ではなく、.db などで ROM に置くデータだけを並べている。
;   11_complete_game.asm の末尾で .include され、プログラムの続きの番地に置かれる。

; ===== パレット (PRG 内) =====
;   ファミコンは画面全体で使える色が限られていて、「4 色 1 組」のパレットを
;   BG 用に 4 組、スプライト用に 4 組の、計 32 バイトで指定する。
;   各組の最初の色（$0f = 黒）は、スプライトでは「透明」として扱われる。
;   値は色そのもの（RGB）ではなく、ファミコンが持つ約 50 色の色番号。
;   load_palette がこの 32 バイトを PPU の $3F00〜$3F1F にコピーする。
palette:
    ; BG パレット 0: スコア表示用（黒背景・白文字）
    .db $0f, $30, $10, $00
    ; BG パレット 1..3: 未使用（ダミー）
    .db $0f, $00, $10, $30
    .db $0f, $00, $10, $30
    .db $0f, $00, $10, $30
    ; スプライトパレット 0: 自機（青／赤／白）
    .db $0f, $12, $16, $30
    ; スプライトパレット 1: 弾（赤／オレンジ／白）
    .db $0f, $16, $27, $30
    ; スプライトパレット 2: 敵（赤／金／灰）
    ;   色 1 = $16（赤／コア・翼の縁・尾）、色 2 = $28（金／本体・王冠）、色 3 = $10（灰／翼の内側）
    .db $0f, $16, $28, $10
    ; スプライトパレット 3: 予備
    .db $0f, $30, $16, $00

; ===== サイン半波テーブル =====
;   sin_half[i] = round(sin(πi/64) * 56)  for i = 0..63
;   値域: 0..56。振幅を 56 に抑えているのは、中心 X（64..191）に足し引きしても
;   8..247 に収まり、敵が画面の反対側へ回り込まないようにするため。
;   実際のサイン波（中心 enemy_center_x、振幅 56）を get_sine_x が
;   このテーブルを読んで作る（前半 0..63 が正、64..127 を負として扱う）。
;   6502 には sin() どころか掛け算の命令も無いので、実行中に計算する代わりに、
;   あらかじめ計算した結果を表にして ROM に置き、添字で引く。
;   計算に時間をかけられないゲーム機では定番の方法（Python で、前計算した値の
;   リストを作っておき table[i] で引くのに近い）。
sin_half:
    .db   0,   3,   5,   8,  11,  14,  16,  19
    .db  21,  24,  26,  29,  31,  33,  36,  38
    .db  40,  41,  43,  45,  47,  48,  49,  51
    .db  52,  53,  54,  54,  55,  55,  56,  56
    .db  56,  56,  56,  55,  55,  54,  54,  53
    .db  52,  51,  49,  48,  47,  45,  43,  41
    .db  40,  38,  36,  33,  31,  29,  26,  24
    .db  21,  19,  16,  14,  11,   8,   5,   3

; ===== 割り込みベクタ =====
;   CPU は、決まった番地に書かれたアドレスを見て、どこから実行するかを決める。
;     $FFFA-$FFFB : NMI が起きたときに飛ぶ先（nmi）
;     $FFFC-$FFFD : 電源投入・リセット時に飛ぶ先（reset）
;     $FFFE-$FFFF : IRQ が起きたときに飛ぶ先（irq）
;   .pad $fffa で、いまの位置から $FFF9 までを 0 で埋めて、次の .dw を $FFFA に置く。
;   .dw は 2 バイト（16 bit）の値を、下位バイト → 上位バイトの順で置く。
    .pad $fffa
    .dw nmi
    .dw reset
    .dw irq

; ===== CHR-ROM ($0000-$1FFF) =====
;   キャラクター（タイル）の絵のデータ。CPU ではなく PPU が読む別の ROM で、
;   .nes ファイルでは PRG-ROM の直後に続く。
;   1 タイル = 8x8 ドット = 16 バイト。1 ドットは 2 bit（色番号 0〜3）で、
;   前半 8 バイト（plane 0）に各ドットの下位ビット、後半 8 バイト（plane 1）に
;   上位ビットを 1 行 1 バイトずつ入れる。2 枚を重ねて色番号が決まる:
;     plane 1 のビット, plane 0 のビット → 色番号  (0,0)→0 (0,1)→1 (1,0)→2 (1,1)→3
;   ビットを 2 枚に分けるのは PPU の回路の都合で、こうしておくと 1 行ぶんの 8 ドットを
;   1 バイトずつ読むだけで描ける。
;   このサンプルでは BG とスプライトが同じタイル表を使う（PPUCTRL の設定による）ので、
;   キャラと文字のタイル番号が重ならないように並べている。
;
;   タイル 0    : 透明
;   タイル 1    : 8x8 べた塗り（互換）
;   タイル 2..5 : 自機 (16x16)
;   タイル 6    : 弾 (8x8)
;   タイル 7..10: 敵 (16x16)
;
; 敵のドット絵 (16x16):
;     R = 色 1 (赤／コア・翼の縁・尾), Y = 色 2 (金／本体・王冠), # = 色 3 (灰／翼の内側)
;
;    Row 0:  ......Y. .Y......   王冠
;    Row 1:  .....RYR RYR.....
;    Row 2:  .....YRR RRY.....
;    Row 3:  ......RR RR......
;    Row 4:  .R...R#Y Y#R...R.
;    Row 5:  .RR.##YY YY##.RR.   翼
;    Row 6:  .RRR##YY YY##RRR.
;    Row 7:  ..RRRYYR RYYRRR..   ← 上下タイルの境
;    Row 8:  ...RRYYR RYYRR...
;    Row 9:  ....RRYR RYRR....
;    Row 10: .....YYR RYY.....
;    Row 11: .....Y.R R.Y.....
;    Row 12: .....Y.R R.Y.....
;    Row 13: .......R R.......   尾
;    Row 14: .......R R.......
;    Row 15: ........ ........
chr_start:
    ; --- タイル 0: 透明 ---
    .db $00, $00, $00, $00, $00, $00, $00, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00

    ; --- タイル 1: 8x8 べた塗り（互換） ---
    .db $ff, $ff, $ff, $ff, $ff, $ff, $ff, $ff
    .db $00, $00, $00, $00, $00, $00, $00, $00

    ; --- タイル 2: 自機 top-left ---
    .db $01, $01, $03, $03, $07, $07, $0f, $17
    .db $01, $01, $01, $01, $00, $00, $00, $08

    ; --- タイル 3: 自機 top-right ---
    .db $80, $80, $c0, $c0, $e0, $e0, $f0, $e8
    .db $80, $80, $80, $80, $00, $00, $00, $10

    ; --- タイル 4: 自機 bottom-left ---
    .db $37, $7f, $df, $df, $c3, $00, $00, $00
    .db $00, $00, $82, $82, $80, $0f, $03, $01

    ; --- タイル 5: 自機 bottom-right ---
    .db $ec, $fe, $fb, $fb, $c3, $00, $00, $00
    .db $00, $00, $41, $41, $01, $f0, $c0, $80

    ; --- タイル 6: 弾（8x8、上が丸く下が尖った火の玉） ---
    .db $3c, $5a, $bd, $99, $66, $24, $3c, $18
    .db $00, $3c, $7e, $7e, $18, $18, $00, $00

    ; --- タイル 7: 敵 top-left ---
    .db $00, $05, $03, $03, $46, $6c, $7c, $39
    .db $02, $02, $04, $00, $03, $0f, $0f, $06

    ; --- タイル 8: 敵 top-right ---
    .db $00, $a0, $c0, $c0, $62, $36, $3e, $9c
    .db $40, $40, $20, $00, $c0, $f0, $f0, $60

    ; --- タイル 9: 敵 bottom-left ---
    .db $19, $0d, $01, $01, $01, $01, $01, $00
    .db $06, $02, $06, $04, $04, $00, $00, $00

    ; --- タイル 10: 敵 bottom-right ---
    .db $98, $b0, $80, $80, $80, $80, $80, $00
    .db $60, $40, $60, $20, $20, $00, $00, $00

    ; --- タイル $0B..$0F: 余り（透明） ---
    ;   .dsb 個数, 値 は「値を個数ぶん並べる」。数字のタイルを $10 から始めたいので、
    ;   残り 5 タイル分（16 × 5 バイト）を 0 で埋めて位置を合わせる。
    .dsb 16 * 5, $00

    ; ----- BG 表示用キャラ ($10..$1E) -----
    ; いずれも plane 0 のみ使用（色 1 = 白）
    ;   文字は 1 色で足りるので plane 1 は全部 0。$10 から '0'〜'9' を順に並べておくと、
    ;   数字 n のタイル番号が $10 + n で求まる（TILE_DIGIT_BASE）。
    ; --- タイル $10: '0' ---
    .db $70, $88, $88, $88, $88, $88, $70, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $11: '1' ---
    .db $20, $60, $20, $20, $20, $20, $70, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $12: '2' ---
    .db $70, $88, $08, $10, $20, $40, $f8, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $13: '3' ---
    .db $f0, $08, $08, $70, $08, $08, $f0, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $14: '4' ---
    .db $10, $30, $50, $90, $f8, $10, $10, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $15: '5' ---
    .db $f8, $80, $80, $f0, $08, $08, $f0, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $16: '6' ---
    .db $70, $80, $80, $f0, $88, $88, $70, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $17: '7' ---
    .db $f8, $08, $10, $20, $40, $40, $40, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $18: '8' ---
    .db $70, $88, $88, $70, $88, $88, $70, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $19: '9' ---
    .db $70, $88, $88, $78, $08, $08, $70, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $1A: 'S' ---
    .db $78, $80, $80, $70, $08, $08, $f0, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $1B: 'C' ---
    .db $78, $80, $80, $80, $80, $80, $78, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $1C: 'O' ---
    .db $70, $88, $88, $88, $88, $88, $70, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $1D: 'R' ---
    .db $f0, $88, $88, $f0, $a0, $90, $88, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $1E: 'E' ---
    .db $f8, $80, $80, $f0, $80, $80, $f8, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00

    ; ----- 11 章で追加するキャラ ($1F..$2B) -----
    ; --- タイル $1F: 'H' ---
    .db $88, $88, $88, $f8, $88, $88, $88, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $20: 'T' ---
    .db $f8, $20, $20, $20, $20, $20, $20, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $21: 'I' ---
    .db $f8, $20, $20, $20, $20, $20, $f8, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $22: 'N' ---
    .db $88, $c8, $a8, $a8, $98, $88, $88, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $23: 'G' ---
    .db $78, $80, $80, $80, $98, $88, $78, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $24: 'P' ---
    .db $f0, $88, $88, $f0, $80, $80, $80, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $25: 'A' ---
    .db $70, $88, $88, $f8, $88, $88, $88, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $26: 'V' ---
    .db $88, $88, $88, $88, $50, $50, $20, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $27: 'M' ---
    .db $88, $d8, $a8, $88, $88, $88, $88, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $28: 'L' ---
    .db $80, $80, $80, $80, $80, $80, $f8, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $29: 'F' ---
    .db $f8, $80, $80, $f0, $80, $80, $80, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $2A: 'x' (小文字、× 風) ---
    .db $00, $00, $88, $50, $20, $50, $88, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00
    ; --- タイル $2B: 'D' ---
    .db $f0, $88, $88, $88, $88, $88, $f0, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00

    ; CHR 残り（8KB まで）を 0 で埋める
    ;   $ は「いまの位置」。$ - chr_start でここまでに置いたバイト数がわかるので、
    ;   8KB（$2000）との差を 0 で埋めると、CHR-ROM がちょうど 8KB になる。
    ;   .nes ファイルのヘッダで CHR-ROM を 8KB と宣言しているため、大きさを合わせる必要がある。
    .dsb $2000 - ($ - chr_start), $00
