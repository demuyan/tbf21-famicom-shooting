; 07_data.asm - パレットと CHR-ROM タイルデータ
;   06 の自機タイル (2..5) に加えて、弾用のタイル 6 を追加。

; ===== パレット (PRG 内) =====
palette:
    ; BG パレット（未使用だがダミー）
    .db $0f, $00, $10, $30
    .db $0f, $00, $10, $30
    .db $0f, $00, $10, $30
    .db $0f, $00, $10, $30
    ; スプライトパレット 0: 自機（青／赤／白）
    .db $0f, $12, $16, $30
    ; スプライトパレット 1: 弾（赤／オレンジ／白）
    ;   色 1 = $16（赤／輪郭）、色 2 = $27（オレンジ／中間）、色 3 = $30（白／芯）
    .db $0f, $16, $27, $30
    .db $0f, $30, $16, $00
    .db $0f, $30, $16, $00

; ===== 割り込みベクタ =====
    .pad $fffa
    .dw nmi
    .dw reset
    .dw irq

; ===== CHR-ROM ($0000-$1FFF) =====
chr_start:
    ; --- タイル 0: 透明 ---
    .db $00, $00, $00, $00, $00, $00, $00, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00

    ; --- タイル 1: 8x8 べた塗り（互換） ---
    .db $ff, $ff, $ff, $ff, $ff, $ff, $ff, $ff
    .db $00, $00, $00, $00, $00, $00, $00, $00

    ; --- タイル 2: 自機 top-left ---
    .db $01, $01, $03, $03, $07, $07, $0f, $17
    .db $01, $01, $01, $01, $00, $00, $00, $08

    ; --- タイル 3: 自機 top-right ---
    .db $80, $80, $c0, $c0, $e0, $e0, $f0, $e8
    .db $80, $80, $80, $80, $00, $00, $00, $10

    ; --- タイル 4: 自機 bottom-left ---
    .db $37, $7f, $df, $df, $c3, $00, $00, $00
    .db $00, $00, $82, $82, $80, $0f, $03, $01

    ; --- タイル 5: 自機 bottom-right ---
    .db $ec, $fe, $fb, $fb, $c3, $00, $00, $00
    .db $00, $00, $41, $41, $01, $f0, $c0, $80

    ; --- タイル 6: 弾（8x8、上が丸く下が尖った火の玉） ---
    ;   . . R R R R . .
    ;   . R O W W O R .   W = 色 3（白）= 芯
    ;   R O W W W W O R
    ;   R O O W W O O R
    ;   . R R O O R R .
    ;   . . R O O R . .
    ;   . . R R R R . .
    ;   . . . R R . . .
    ;   R = 色 1 (赤), O = 色 2 (オレンジ), W = 色 3 (白)
    ; plane 0 (色 1 と 3 で立つビット)
    .db $3c, $5a, $bd, $99, $66, $24, $3c, $18
    ; plane 1 (色 2 と 3 で立つビット)
    .db $00, $3c, $7e, $7e, $18, $18, $00, $00

    ; CHR 残り（8KB まで）を 0 で埋める
    .dsb $2000 - ($ - chr_start), $00
