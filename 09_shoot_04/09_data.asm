; 09_data.asm - パレット、サインテーブル、CHR-ROM
;   07 の自機 (タイル 2..5) と弾 (タイル 6) に加えて、敵 (タイル 7..10) を追加。

; ===== パレット (PRG 内) =====
palette:
    ; BG パレット（未使用だがダミー）
    .db $0f, $00, $10, $30
    .db $0f, $00, $10, $30
    .db $0f, $00, $10, $30
    .db $0f, $00, $10, $30
    ; スプライトパレット 0: 自機（青／赤／白）
    .db $0f, $12, $16, $30
    ; スプライトパレット 1: 弾（赤／オレンジ／白）
    .db $0f, $16, $27, $30
    ; スプライトパレット 2: 敵（赤／金／灰）
    ;   色 1 = $16（赤／コア・翼の縁・尾）、色 2 = $28（金／本体・王冠）、色 3 = $10（灰／翼の内側）
    .db $0f, $16, $28, $10
    ; スプライトパレット 3: 予備
    .db $0f, $30, $16, $00

; ===== サイン半波テーブル =====
;   sin_half[i] = round(sin(πi/64) * 112)  for i = 0..63
;   値域: 0..112。実際のサイン波（中心 128、振幅 112）を get_sine_x が
;   このテーブルを読んで作る（前半 0..63 が正、64..127 を負として扱う）。
sin_half:
    .db   0,   5,  11,  16,  22,  27,  33,  38
    .db  43,  48,  53,  58,  62,  67,  71,  75
    .db  79,  83,  87,  90,  93,  96,  99, 101
    .db 103, 105, 107, 109, 110, 111, 111, 112
    .db 112, 112, 111, 111, 110, 109, 107, 105
    .db 103, 101,  99,  96,  93,  90,  87,  83
    .db  79,  75,  71,  67,  62,  58,  53,  48
    .db  43,  38,  33,  27,  22,  16,  11,   5

; ===== 割り込みベクタ =====
    .pad $fffa
    .dw nmi
    .dw reset
    .dw irq

; ===== CHR-ROM ($0000-$1FFF) =====
;   タイル 0    : 透明
;   タイル 1    : 8x8 べた塗り（互換）
;   タイル 2..5 : 自機 (16x16)
;   タイル 6    : 弾 (8x8)
;   タイル 7..10: 敵 (16x16)
;
; 敵のドット絵 (16x16):
;     R = 色 1 (赤／コア・翼の縁・尾), Y = 色 2 (金／本体・王冠), # = 色 3 (灰／翼の内側)
;
;    Row 0:  ......Y. .Y......   王冠
;    Row 1:  .....RYR RYR.....
;    Row 2:  .....YRR RRY.....
;    Row 3:  ......RR RR......
;    Row 4:  .R...R#Y Y#R...R.
;    Row 5:  .RR.##YY YY##.RR.   翼
;    Row 6:  .RRR##YY YY##RRR.
;    Row 7:  ..RRRYYR RYYRRR..   ← 上下タイルの境
;    Row 8:  ...RRYYR RYYRR...
;    Row 9:  ....RRYR RYRR....
;    Row 10: .....YYR RYY.....
;    Row 11: .....Y.R R.Y.....
;    Row 12: .....Y.R R.Y.....
;    Row 13: .......R R.......   尾
;    Row 14: .......R R.......
;    Row 15: ........ ........
chr_start:
    ; --- タイル 0: 透明 ---
    .db $00, $00, $00, $00, $00, $00, $00, $00
    .db $00, $00, $00, $00, $00, $00, $00, $00

    ; --- タイル 1: 8x8 べた塗り（互換） ---
    .db $ff, $ff, $ff, $ff, $ff, $ff, $ff, $ff
    .db $00, $00, $00, $00, $00, $00, $00, $00

    ; --- タイル 2: 自機 top-left ---
    .db $01, $01, $03, $03, $07, $07, $0f, $17
    .db $01, $01, $01, $01, $00, $00, $00, $08

    ; --- タイル 3: 自機 top-right ---
    .db $80, $80, $c0, $c0, $e0, $e0, $f0, $e8
    .db $80, $80, $80, $80, $00, $00, $00, $10

    ; --- タイル 4: 自機 bottom-left ---
    .db $37, $7f, $df, $df, $c3, $00, $00, $00
    .db $00, $00, $82, $82, $80, $0f, $03, $01

    ; --- タイル 5: 自機 bottom-right ---
    .db $ec, $fe, $fb, $fb, $c3, $00, $00, $00
    .db $00, $00, $41, $41, $01, $f0, $c0, $80

    ; --- タイル 6: 弾（8x8、上が丸く下が尖った火の玉） ---
    .db $3c, $5a, $bd, $99, $66, $24, $3c, $18
    .db $00, $3c, $7e, $7e, $18, $18, $00, $00

    ; --- タイル 7: 敵 top-left ---
    .db $00, $05, $03, $03, $46, $6c, $7c, $39
    .db $02, $02, $04, $00, $03, $0f, $0f, $06

    ; --- タイル 8: 敵 top-right ---
    .db $00, $a0, $c0, $c0, $62, $36, $3e, $9c
    .db $40, $40, $20, $00, $c0, $f0, $f0, $60

    ; --- タイル 9: 敵 bottom-left ---
    .db $19, $0d, $01, $01, $01, $01, $01, $00
    .db $06, $02, $06, $04, $04, $00, $00, $00

    ; --- タイル 10: 敵 bottom-right ---
    .db $98, $b0, $80, $80, $80, $80, $80, $00
    .db $60, $40, $60, $20, $20, $00, $00, $00

    ; CHR 残り（8KB まで）を 0 で埋める
    .dsb $2000 - ($ - chr_start), $00
